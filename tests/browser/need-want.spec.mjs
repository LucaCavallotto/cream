import { test, expect, launch, openRows, row, tab, saveModal, downloadRows } from './fixtures.mjs';

test('need/want supports editing bulk assignment clearing export and scoped statistics', async ({page}) => {
  await launch(page);
  await openRows(page,[row('Rent',-100),row('Fun',-50),row('Salary',1000,'Income','Salary')]);
  await page.locator('#transactionsTbody .mobile-row-click').filter({hasText:'Rent'}).first().click();
  await expect(page.locator('#inputNeedWant')).toHaveValue('');
  await page.locator('#inputNeedWant').selectOption('need');
  await saveModal(page);
  await tab(page,'Overview');
  const overview=page.locator('#overview-tab-pane .need-want-summary');
  await expect(overview).toContainText('Need€100.00');
  await expect(overview).toContainText('Not classified€50.00');
  await tab(page,'Analytics');
  await page.locator('#analyticsTimePeriod').selectOption('overall');
  await expect(page.locator('#analytics-tab-pane .need-want-summary')).toContainText('Need€100.00');
  await tab(page,'Transactions');
  await page.locator('#btnSelectMode').click();
  await page.locator('#selectAllCheckbox').check();
  page.on('dialog',d=>d.accept());
  await page.locator('#bulkNeedWant').selectOption('want');
  await page.locator('#btnBulkApplyNeedWant').click();
  await tab(page,'Overview');
  await expect(overview).toContainText('Want€150.00');
  await tab(page,'Analytics');
  await page.getByText('Exclude categories', {exact:true}).click();
  await page.locator('#analyticsExcludeCategory').selectOption(JSON.stringify('Bar'));
  await page.locator('#analyticsAddExclusion').click();
  await expect(page.locator('#analytics-tab-pane .need-want-summary')).toContainText('Want€0.00');
  await page.locator('#analyticsIncludeAll').click();
  await expect(page.locator('#analytics-tab-pane .need-want-summary')).toContainText('Want€150.00');
  await tab(page,'Transactions');
  await page.locator('#btnSelectMode').click();
  await page.locator('#selectAllCheckbox').check();
  await page.locator('#bulkNeedWant').selectOption('');
  await page.locator('#btnBulkApplyNeedWant').click();
  const saved=await downloadRows(page);
  expect(saved.rows.every(r=>r.NeedWant==='')).toBe(true);
  await tab(page,'Overview');
  await expect(overview).toContainText('Not classified€150.00');
  await page.setViewportSize({width:390,height:900});
  await page.emulateMedia({colorScheme:'dark'});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
